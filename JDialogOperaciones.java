    private void jButtonShowDevicesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jButtonShowDevicesMouseClicked
        // TODO add your handling code here:
        try (resetPwdAppDAOImplementation uDao = new resetPwdAppDAOImplementation(padre.url)) {
                    DefaultTableModel miTabla = (DefaultTableModel) this.jTableDevices.getModel();
                    miTabla.setNumRows(0);
                    for(Dispositivos e: uDao.getDevices()){
                        Object[] datos = {e.getDeviceName(), e.isEnabled(), e.getFwVersion(), e.getCommType(), e.getIpAdress(), e.getGateway(), e.getSubnetMask(), e.getPort(), e.getSn(), e.getId()};
                        miTabla.addRow(datos);
                    }
                } catch (Exception ex) {
                    System.out.println(ex.getClass() + " " + ex.getMessage());
                }
    }//GEN-LAST:event_jButtonShowDevicesMouseClicked
    
    private void jButtonModifyDevicesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jButtonModifyDevicesMouseClicked
        // TODO add your handling code here:
        DefaultTableModel modelo = (DefaultTableModel) this.jTableDevices.getModel();
        int filas = modelo.getRowCount();
        try (resetPwdAppDAOImplementation uDao = new resetPwdAppDAOImplementation(padre.url)) {

            for (int i = 0; i < filas; i++) {
                boolean estadoActual = (Boolean) modelo.getValueAt(i, 1);
                String idDispositivo = (String) modelo.getValueAt(i, 9);
                uDao.updateDeviceEnabled(idDispositivo, estadoActual);
            }

            System.out.println("Se han actualizado " + filas + " dispositivos en la base de datos.");

        } catch (Exception ex) {
            System.out.println("Error al guardar: " + ex.getMessage());
        }
    }//GEN-LAST:event_jButtonModifyDevicesMouseClicked

